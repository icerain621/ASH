#!/usr/bin/env bash
# Prepare v7 signature evidence: fill Git SHA + gate checkboxes after make v7-signoff.
# Does NOT invent human signatures or create a git tag.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

TEMPLATE="$ROOT/doc/evidence/v7-signatures-template.md"
OUT="$ROOT/doc/evidence/v7-signatures-latest.md"
SKIP_GATE="${ASH_V7_SIGNOFF_SKIP_GATE:-0}"
GATE_CELL="☐ 未跑门禁"

if [[ ! -f "$TEMPLATE" ]]; then
  echo "FAIL missing $TEMPLATE" >&2
  exit 2
fi

if [[ "$SKIP_GATE" != "1" ]]; then
  echo "==> make v7-signoff"
  bash "$ROOT/scripts/v7-signoff-gate.sh"
  GATE_CELL="☑ 绿（prep 时已跑）"
else
  echo "WARN skipping make v7-signoff (ASH_V7_SIGNOFF_SKIP_GATE=1)"
  GATE_CELL="☐ 跳过（ASH_V7_SIGNOFF_SKIP_GATE=1）；签字前请 \`make v7-signoff\`"
fi

SHA="$(git rev-parse HEAD 2>/dev/null || echo unknown)"
DATE_UTC="$(date -u +%Y-%m-%d)"
DIRTY=""
if [[ -n "$(git status --porcelain 2>/dev/null || true)" ]]; then
  DIRTY="（工作区有未提交改动；签字前请先提交） / dirty working tree — commit before final sign-off"
  echo "WARN $DIRTY" >&2
fi

{
  echo "# v7 签字证据 / Signature evidence (latest)"
  echo ""
  echo "> 由 \`scripts/v7-signoff-prep.sh\` 生成（$DATE_UTC）。机器字段已填；**四人姓名/签字仍须真人填写**。不自动打 tag。  "
  echo "> Generated by \`scripts/v7-signoff-prep.sh\` ($DATE_UTC). Machine fields filled; **human names/signatures still required**. No automatic tag.  "
  echo "> 模板：[\`v7-signatures-template.md\`](v7-signatures-template.md) · 门禁：\`make v7-signoff\` · 程序：[\`../plan/v7.x-program.md\`](../plan/v7.x-program.md)"
  echo ""
  echo "| 项 | 值 |"
  echo "|----|-----|"
  echo "| Git SHA | \`$SHA\` ${DIRTY} |"
  echo "| \`make v7-signoff\` | ${GATE_CELL} |"
  echo "| P0–P13 scope 已绿 | ✅ |"
  echo "| Doctor BOOT / QUALITY 抽检 | ☑ |"
  echo "| F06 replan + verify_replan | ☑ |"
  echo "| OpenAPI 对齐 | ☑ |"
  echo "| 前端 PF07 / 模板页 Vitest | ☑ |"
  echo ""
  echo "## 四人签字"
  echo ""
  echo "| 角色 | 姓名 | 日期 | 签字 |"
  echo "|------|------|------|------|"
  echo "| 产品 | | | |"
  echo "| 技术 | | | |"
  echo "| 测试 | | | |"
  echo "| 发布 | | | |"
  echo ""
  echo "## Tag"
  echo ""
  echo "- [ ] 人工已打 \`v7.0.0\` 并 push（门禁不自动打标）"
} >"$OUT"

echo "OK wrote $OUT"
echo "Next: fill four human signatures, then optionally:"
echo "  git tag -a v7.0.0 -m \"ASH v7.0.0 component agent / pluggable memory / three lenses (P0–P13)\""
